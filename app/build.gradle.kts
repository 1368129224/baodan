fun getGitCommitHash(): String {
    return try {
        val stdout = ByteArrayOutputStream()
        project.exec {
            commandLine = listOf("git", "rev-parse", "--short", "HEAD")
            standardOutput = stdout
        }
        stdout.toString().trim()
    } catch (e: Exception) {
        "dev"
    }
}

